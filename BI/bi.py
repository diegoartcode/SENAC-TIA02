# Quatro níveis de pergunta em análise de dados
# Descritiva
    # O que aconteceu?
        # Qual loja faturou mais no mês passado?
# Diagnóstica
    # Por que aconteceu?
        # Por que a loja "CENTRO" vendeu menos?
# Preditiva
    # O que pode acontecer?
        # Quanto a loja "LAPA" venderá no próximo mês?
# Prescritiva
    # O que devemos fazer?
        # Quanto estoque comprar para o próximo mês?


