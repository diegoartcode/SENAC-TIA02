#operadores comparacao
num1 = 35
num2 = 3

igualdade = num1 == num2 # False
diferente = num1 != num2 # True
maior_que = num1 > num2 # True
menor_que = num1 < num2 # False
maior_igual = num1 >= num2 # True
menor_igual = num1 <= num2 # False

print(igualdade)
print(diferente)
print(maior_que)
print(menor_que)
print(maior_igual)
print(menor_igual)

